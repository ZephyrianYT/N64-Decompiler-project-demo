"""Write a buildable C project from an analyzed ROM, and compile it.

Output layout:

    <out>/
      src/recomp.h          prototypes for every recompiled function
      src/funcs_000.c ...   the recompiled functions (one C function per MIPS function)
      src/game_info.c       ROM details, function table for indirect calls
      runtime/              the hand-written C runtime (memory, hardware, window)
      asm/<name>.s          the disassembly the C was generated from
      build.bat, Makefile, CMakeLists.txt
"""

import json
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

from .analysis import Program, Segment, load_symbols
from .codegen import c_ident, func_ident, generate_function
from .rom import GAME_START

RUNTIME_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "runtime")
# Split the output so files compile in parallel and stay a manageable size.
INSTRUCTIONS_PER_FILE = 6000
BOOT_SEGMENT_SIZE = 0x100000


def _int(value):
    return value if isinstance(value, int) else int(str(value), 0)


def load_config(path):
    if not path:
        return {}
    with open(path, encoding="utf-8") as f:
        config = json.load(f)
    config["_dir"] = os.path.dirname(os.path.abspath(path))
    return config


def make_program(rom, config=None):
    """Build and analyze a Program from a ROM and an optional config dict."""
    config = config or {}
    boot_size = min(BOOT_SEGMENT_SIZE, len(rom.data) - GAME_START)
    segments = [Segment("boot", GAME_START, rom.entry, boot_size)]
    for seg in config.get("segments", []):
        segments.append(Segment(seg.get("name", "segment"), _int(seg["rom"]), _int(seg["vram"]),
                                _int(seg["size"])))
    symbols = {}
    if config.get("symbols"):
        symbols = load_symbols(os.path.join(config.get("_dir", "."), config["symbols"]))
    if config.get("_symbols_file"):
        symbols.update(load_symbols(config["_symbols_file"]))
    for addr, name in config.get("names", {}).items():
        symbols[_int(addr)] = name
    program = Program(
        rom, segments, symbols,
        extra_functions=[_int(a) for a in config.get("functions", [])],
        stubs=[_int(a) for a in config.get("stubs", [])],
    )
    return program.analyze()


def disassemble_function(program, func):
    lines = ["", "glabel %s  # 0x%08X, %s" % (func.name, func.start, func.reason)]
    for warning in func.warnings:
        lines.append("    # WARNING: %s" % warning)
    for insn in func.insns:
        if insn.addr in func.labels and insn.addr != func.start:
            lines.append(".L%08X:" % insn.addr)
        lines.append("    /* %08X %08X */  %s" % (insn.addr, insn.word, insn.text(program.symbols)))
        if insn.addr in func.jump_tables:
            table = func.jump_tables[insn.addr]
            lines.append("    # jump table at 0x%08X: %d entries" % (table.table_addr, len(table.targets)))
    return "\n".join(lines)


def summary(program):
    funcs = list(program.functions.values())
    insns = sum(len(f.insns) for f in funcs)
    tables = sum(len(f.jump_tables) for f in funcs)
    warnings = sum(len(f.warnings) for f in funcs)
    return ("%d functions, %d instructions, %d jump tables, %d warnings"
            % (len(funcs), insns, tables, warnings))


def write_project(program, out_dir, project_name=None, jobs=None):
    rom = program.rom
    name = c_ident(project_name or rom.title or "game")
    src = os.path.join(out_dir, "src")
    asm = os.path.join(out_dir, "asm")
    runtime = os.path.join(out_dir, "runtime")
    for d in (src, asm, runtime):
        os.makedirs(d, exist_ok=True)
    for old in os.listdir(src):
        if old.startswith("funcs_") and old.endswith(".c"):
            os.remove(os.path.join(src, old))
    for fname in os.listdir(RUNTIME_DIR):
        if fname.endswith((".c", ".h")):
            shutil.copy(os.path.join(RUNTIME_DIR, fname), os.path.join(runtime, fname))

    funcs = [program.functions[a] for a in sorted(program.functions)]
    _make_names_unique(funcs)

    with open(os.path.join(src, "recomp.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by n64lab: prototypes for every recompiled function. */\n")
        f.write("#ifndef RECOMP_H\n#define RECOMP_H\n#include \"n64_runtime.h\"\n\n")
        for func in funcs:
            f.write("void %s(CPUState* cpu);\n" % func_ident(func))
        f.write("\n#endif\n")

    chunks = [[f.start for f in chunk] for chunk in _chunks(funcs)]
    for n, text in enumerate(_generate_chunks(program, chunks, jobs)):
        with open(os.path.join(src, "funcs_%03d.c" % n), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

    with open(os.path.join(src, "game_info.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write(_game_info(program, funcs))

    with open(os.path.join(asm, "%s.s" % name), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Disassembly of %s (%s), as seen by the recompiler\n" % (rom.title, rom.game_code))
        for func in funcs:
            f.write(disassemble_function(program, func) + "\n")

    _write_build_files(out_dir, name)
    return name


# -- parallel code generation --------------------------------------------------------
# Translating functions is independent work, but Python threads cannot run it
# in parallel (the GIL), so on Linux large ROMs use forked worker processes that
# turn lists of function addresses into finished C files.

PARALLEL_THRESHOLD = 40000   # instructions; below this, process start-up costs more than it saves
_worker_program = None


def _init_worker(program):
    global _worker_program
    _worker_program = program


def _chunk_text(program, starts):
    first, last = starts[0], starts[-1]
    parts = ["/* Generated by n64lab from \"%s\" - functions 0x%08X to 0x%08X. */\n"
             % (program.rom.title, first, last), "#include \"recomp.h\"\n"]
    for start in starts:
        parts.append("\n" + generate_function(program, program.functions[start]))
    return "".join(parts)


def _worker_chunk(starts):
    return _chunk_text(_worker_program, starts)


def _generate_chunks(program, chunks, jobs=None):
    import multiprocessing
    jobs = jobs or os.cpu_count() or 1
    total = sum(len(program.functions[s].insns) for chunk in chunks for s in chunk)
    # Workers only pay off with "fork" (Linux), which shares the analyzed program
    # with them for free.  With "spawn" (Windows, macOS) each worker must be sent
    # a pickled copy first, which measured slower than doing the work serially.
    can_fork = sys.platform == "linux" and "fork" in multiprocessing.get_all_start_methods()
    if not can_fork or jobs <= 1 or len(chunks) <= 1 or total < PARALLEL_THRESHOLD:
        return [_chunk_text(program, chunk) for chunk in chunks]
    from concurrent.futures import ProcessPoolExecutor
    with ProcessPoolExecutor(max_workers=min(jobs, len(chunks)), mp_context=multiprocessing.get_context("fork"),
                             initializer=_init_worker, initargs=(program,)) as pool:
        return list(pool.map(_worker_chunk, chunks))


def _chunks(funcs):
    chunk, size = [], 0
    for func in funcs:
        if chunk and size + len(func.insns) > INSTRUCTIONS_PER_FILE:
            yield chunk
            chunk, size = [], 0
        chunk.append(func)
        size += len(func.insns)
    if chunk:
        yield chunk


def _make_names_unique(funcs):
    seen = set()
    for func in funcs:
        if func_ident(func) in seen:
            func.name = "%s_%08X" % (func.name, func.start)
        seen.add(func_ident(func))


def _c_string(text):
    return '"%s"' % "".join(ch if 32 <= ord(ch) < 127 and ch not in '"\\' else "\\x%02X" % (ord(ch) & 0xFF)
                            for ch in text)


def _game_info(program, funcs):
    rom = program.rom
    boot = program.segments[0]
    entry = program.functions.get(rom.entry)
    lines = [
        "/* Generated by n64lab: ROM details and the table used for indirect calls. */",
        "#include \"recomp.h\"",
        "",
        "const N64GameInfo n64_game = {",
        "    %s, %s," % (_c_string(rom.title or "untitled"), _c_string(rom.game_code)),
        "    0x%08X, 0x%08X," % rom.header_crc,
        "    0x%08X, 0x%X, 0x%X," % (rom.entry, boot.rom_start, boot.size),
        "};",
        "",
        "/* Sorted by address so the runtime can binary-search it. */",
        "const N64FunctionEntry n64_functions[] = {",
    ]
    for func in funcs:
        lines.append("    {0x%08X, %s, %s}," % (func.start, func_ident(func), _c_string(func.name)))
    lines += [
        "};",
        "const size_t n64_function_count = sizeof n64_functions / sizeof n64_functions[0];",
        "",
        "void n64_game_entry(CPUState* cpu) {",
        "    %s;" % ("%s(cpu)" % func_ident(entry) if entry else "n64_call(cpu, 0x%08X)" % rom.entry),
        "}",
        "",
    ]
    return "\n".join(lines)


def _write_build_files(out_dir, name):
    with open(os.path.join(out_dir, "build.bat"), "w", newline="\r\n") as f:
        f.write(BUILD_BAT.replace("@NAME@", name))
    with open(os.path.join(out_dir, "Makefile"), "w", newline="\n") as f:
        f.write(MAKEFILE.replace("@NAME@", name))
    with open(os.path.join(out_dir, "CMakeLists.txt"), "w", newline="\n") as f:
        f.write(CMAKELISTS.replace("@NAME@", name))


# -- compiling ----------------------------------------------------------------------

PROBE_SOURCE = """#include <stdio.h>
#include <math.h>
#ifdef _WIN32
#include <windows.h>
#endif
int main(void) { printf("%f", sqrt(2.0)); return 0; }
"""


def _compiler_works(cc, windows):
    """Compile and link a tiny program, to catch e.g. clang installed without its C library."""
    import tempfile
    with tempfile.TemporaryDirectory(prefix="n64lab_probe_") as tmp:
        src = os.path.join(tmp, "probe.c")
        with open(src, "w") as f:
            f.write(PROBE_SOURCE)
        if os.path.basename(cc).lower() in ("cl", "cl.exe"):
            cmd = [cc, "/nologo", src, "/Fe" + os.path.join(tmp, "probe.exe"), "/Fo" + tmp + os.sep]
        else:
            cmd = [cc, src, "-o", os.path.join(tmp, "probe.exe" if windows else "probe")]
            cmd += ["-luser32", "-lgdi32"] if windows else ["-lm"]
        try:
            return subprocess.run(cmd, capture_output=True, timeout=120).returncode == 0
        except (OSError, subprocess.TimeoutExpired):
            return False


_compiler_cache = {}


def find_compiler(target):
    """Return a working C compiler command for `target` ("native" or "windows")."""
    if target in _compiler_cache:
        return _compiler_cache[target]
    on_windows = sys.platform == "win32"
    # clang is preferred: it compiles the very large generated functions several
    # times faster than gcc.
    if target == "windows" and not on_windows:
        candidates = ["x86_64-w64-mingw32-clang", "x86_64-w64-mingw32-gcc"]
    else:
        candidates = ["clang", "gcc", "cc"] + (["cl"] if on_windows else [])
    found = None
    for cc in candidates:
        if shutil.which(cc) and _compiler_works(cc, target == "windows" or on_windows):
            found = cc
            break
    _compiler_cache[target] = found
    return found


def compile_project(out_dir, name, target="native", cc=None, opt="-O1", jobs=None, log=print):
    """Compile every .c file in parallel, then link.  Returns the executable path."""
    cc = cc or find_compiler(target)
    if not cc:
        raise RuntimeError("no C compiler found for target '%s' (install gcc, clang, MinGW or MSVC)" % target)
    windows = target == "windows" or sys.platform == "win32"
    exe = os.path.join(out_dir, name + (".exe" if windows else ""))
    sources = [os.path.join("src", f) for f in sorted(os.listdir(os.path.join(out_dir, "src"))) if f.endswith(".c")]
    sources += [os.path.join("runtime", f) for f in sorted(os.listdir(os.path.join(out_dir, "runtime")))
                if f.endswith(".c")]
    obj_dir = os.path.join(out_dir, "build")
    os.makedirs(obj_dir, exist_ok=True)
    msvc = os.path.basename(cc).lower() in ("cl", "cl.exe")

    def compile_one(source):
        obj = os.path.join("build", os.path.basename(source)[:-2] + (".obj" if msvc else ".o"))
        if msvc:
            cmd = [cc, "/nologo", "/std:c11", "/O1" if opt != "-O0" else "/Od", "/Iruntime", "/Isrc",
                   "/c", source, "/Fo" + obj]
        else:
            cmd = [cc, "-std=c11", opt, "-Iruntime", "-Isrc", "-c", source, "-o", obj]
        result = subprocess.run(cmd, cwd=out_dir, capture_output=True, text=True)
        return source, obj, result

    log("compiling %d files with %s..." % (len(sources), cc))
    objects = []
    with ThreadPoolExecutor(max_workers=jobs or os.cpu_count() or 2) as pool:
        for source, obj, result in pool.map(compile_one, sources):
            if result.returncode != 0:
                raise RuntimeError("compiling %s failed:\n%s%s" % (source, result.stdout, result.stderr))
            objects.append(obj)

    if msvc:
        cmd = [cc, "/nologo", "/Fe" + os.path.basename(exe)] + objects + ["user32.lib", "gdi32.lib"]
    else:
        cmd = [cc] + objects + ["-o", os.path.basename(exe)]
        cmd += ["-luser32", "-lgdi32"] if windows else ["-lm", "-lpthread"]
    result = subprocess.run(cmd, cwd=out_dir, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError("linking failed:\n%s%s" % (result.stdout, result.stderr))
    return exe


BUILD_BAT = r"""@echo off
rem Rebuild @NAME@.exe from the generated C.  Uses gcc/clang (MinGW, MSYS2, LLVM) or MSVC.
cd /d "%~dp0"
where clang >nul 2>&1 && (
    clang -std=c11 -O1 -Iruntime -Isrc src\*.c runtime\*.c -o @NAME@.exe -luser32 -lgdi32 && goto done
    goto failed
)
where gcc >nul 2>&1 && (
    gcc -std=c11 -O1 -Iruntime -Isrc src\*.c runtime\*.c -o @NAME@.exe -lm -luser32 -lgdi32 && goto done
    goto failed
)
where cl >nul 2>&1 && (
    cl /nologo /std:c11 /O1 /Iruntime /Isrc src\*.c runtime\*.c /Fe@NAME@.exe user32.lib gdi32.lib && goto done
    goto failed
)
echo No C compiler found. Install MinGW-w64, LLVM, or Visual Studio Build Tools.
goto failed
:done
echo Built @NAME@.exe - drag your ROM onto it to run.
exit /b 0
:failed
pause
exit /b 1
"""

MAKEFILE = """# Rebuild @NAME@ from the generated C.  `make` for this machine,
# `make windows` to cross-compile a Windows .exe with MinGW.
CC ?= cc
CFLAGS ?= -std=c11 -O1
SRC := $(wildcard src/*.c) $(wildcard runtime/*.c)

@NAME@: $(SRC)
\t$(CC) $(CFLAGS) -Iruntime -Isrc $(SRC) -o $@ -lm -lpthread

windows: $(SRC)
\tx86_64-w64-mingw32-gcc $(CFLAGS) -Iruntime -Isrc $(SRC) -o @NAME@.exe -lm -luser32 -lgdi32

.PHONY: windows
""".replace("\\t", "\t")

CMAKELISTS = """cmake_minimum_required(VERSION 3.13)
project(@NAME@ C)
set(CMAKE_C_STANDARD 11)
file(GLOB SOURCES src/*.c runtime/*.c)
add_executable(@NAME@ ${SOURCES})
target_include_directories(@NAME@ PRIVATE src runtime)
if(WIN32)
  target_link_libraries(@NAME@ user32 gdi32)
else()
  find_package(Threads REQUIRED)
  target_link_libraries(@NAME@ m Threads::Threads)
endif()
"""
